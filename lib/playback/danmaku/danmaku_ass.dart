import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:path_provider/path_provider.dart';

import '../../data/danmaku/danmaku.dart';

/// Turns a list of [Danmaku] into a SubStation Alpha file and writes it to a
/// temp path, so the player can render it as a *secondary* subtitle track.
///
/// Because it is a real subtitle track, mpv drives the timing: seeking,
/// pausing and speed changes are followed for free — no per-frame Dart work.
abstract final class DanmakuAss {
  /// Scroll duration shrinks with text length so long lines do not pile up.
  static int _scrollMs(String text) => (6000 + text.runes.length * 120).clamp(6000, 14000);
  static const _staticMs = 5000;

  static String _stamp(int ms) {
    if (ms < 0) ms = 0;
    final cs = (ms / 10) % 100;
    final s = (ms ~/ 1000) % 60;
    final m = (ms ~/ 60000) % 60;
    final h = ms ~/ 3600000;
    return '${h.toString().padLeft(2, '0')}:${m.toString().padLeft(2, '0')}:${s.toString().padLeft(2, '0')}.${cs.toString().padLeft(2, '0')}';
  }

  static String _escape(String text) => text
      .replaceAll('\\', r'\\')
      .replaceAll('{', r'\{')
      .replaceAll('}', r'\}')
      .replaceAll('\r', '')
      .replaceAll('\n', r'\N');

  /// ASS colour is &HBBGGRR&. null keeps the style default (white).
  static String _colorOverride(int? color) {
    if (color == null) return '';
    final r = (color >> 16) & 0xFF;
    final g = (color >> 8) & 0xFF;
    final b = color & 0xFF;
    final bgr = (b << 16) | (g << 8) | r;
    return '\\1c&H${bgr.toRadixString(16).padLeft(6, '0').toUpperCase()}&';
  }

  /// Build the full ASS document. [playResX]/[playResY] set the layout canvas
  /// so scroll lanes and top/bottom margins scale with the video.
  static String render(
    List<Danmaku> items, {
    int playResX = 1280,
    int playResY = 720,
    double scale = 1.0,
  }) {
    final fontSize = (28 * scale).round();
    final marginV = (playResY * 0.08).round();
    final sb = StringBuffer();
    sb.writeln('[Script Info]');
    sb.writeln('; Generated by AusHD Player danmaku overlay');
    sb.writeln('ScriptType: v4.00+');
    sb.writeln('PlayResX: $playResX');
    sb.writeln('PlayResY: $playResY');
    sb.writeln('WrapStyle: 2');
    sb.writeln('ScaledBorderAndShadow: yes');
    sb.writeln();
    sb.writeln('[V4+ Styles]');
    sb.writeln('Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeThrough, Scaling, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding');
    const white = '&H00FFFFFF';
    final opaque = '&H00000000';
    // 8 scroll lanes share one style; per-line \\y moves them vertically.
    sb.writeln('Style: Scroll,Noto Sans CJK SC,$fontSize,$white,$white,&H00101010,$opaque,0,0,0,0,100,0,1,2,0,7,40,40,0,1');
    sb.writeln('Style: Top,Noto Sans CJK SC,$fontSize,$white,$white,&H00101010,$opaque,0,0,0,0,100,0,1,2,0,8,40,40,$marginV,1');
    sb.writeln('Style: Bottom,Noto Sans CJK SC,$fontSize,$white,$white,&H00101010,$opaque,0,0,0,0,100,0,1,2,0,2,40,40,$marginV,1');
    sb.writeln();
    sb.writeln('[Events]');
    sb.writeln('Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text');
    // Round-robin lane assignment so simultaneous scrolls do not overlap.
    const lanes = 8;
    var laneCursor = 0;
    for (final d in items) {
      if (d.text.isEmpty) continue;
      final style = switch (d.mode) {
        DanmakuMode.top => 'Top',
        DanmakuMode.bottom => 'Bottom',
        DanmakuMode.scroll => 'Scroll',
      };
      final dur = d.mode == DanmakuMode.scroll ? _scrollMs(d.text) : _staticMs;
      final overrides = <String>[];
      if (d.color != null) overrides.add(_colorOverride(d.color));
      if (d.fontSize != null) overrides.add('\\fs${(d.fontSize! * scale).round()}');
      if (d.mode == DanmakuMode.scroll) {
        final lane = laneCursor++ % lanes;
        // \\move(x1,y, x2,y) drives the right-to-left scroll at constant speed.
        final y = (playResY * 0.08 + lane * fontSize * 1.4).round();
        final x1 = playResX + 200;
        final x2 = -(fontSize * (d.text.runes.length + 2)).clamp(200, playResX + 200);
        overrides.add('\\move($x1,$y,$x2,$y)');
      }
      final prefix = overrides.isEmpty ? '' : '{${overrides.join('')}}';
      sb.writeln('Dialogue: 0,${_stamp(d.timeMs)},${_stamp(d.timeMs + dur)},$style,,0,0,0,,${prefix}${_escape(d.text)}');
    }
    return sb.toString();
  }

  /// Write [items] as an ASS file under the cache dir and return its path.
  /// An empty list still writes a valid (event-less) file so the caller can
  /// safely attach it and later detach without special-casing.
  static Future<String> writeTemp(List<Danmaku> items, {required String key, double scale = 1.0}) async {
    final dir = Directory(p.join((await getTemporaryDirectory()).path, 'aushd_danmaku'));
    if (!await dir.exists()) await dir.create(recursive: true);
    final safe = key.replaceAll(RegExp(r'[^A-Za-z0-9._-]'), '_');
    final file = File(p.join(dir.path, '$safe.ass'));
    await file.writeAsString(render(items, scale: scale), encoding: utf8, flush: true);
    return file.path;
  }
}
